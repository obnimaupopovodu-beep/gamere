import { Entity, LevelDef } from '../types.ts';

const E = (kind: Entity['kind'], id: string, x: number, y: number, opt: Partial<Entity> = {}): Entity => ({ kind, id, x, y, ...opt });
const sw = (id: string, x: number, y: number, role: 'fire' | 'water', opt: Partial<Entity> = {}) => E('switch', id, x, y, { role, ...opt });
const pl = (id: string, x: number, y: number, opt: Partial<Entity> = {}) => E('plate', id, x, y, opt);
const box = (id: string, x: number, y: number) => E('box', id, x, y, { carrier: null });
const gate = (id: string, x: number, y: number, w: number, h: number, req: string, opt: Partial<Entity> = {}) => E('gate', id, x, y, { w, h, req, ...opt });
const hazard = (id: string, x: number, y: number, w: number, h: number, type: 'laser' | 'heat' | 'water' | 'pulse', off?: string) => E('hazard', id, x, y, { w, h, type, off });
const ferry = (id: string, x: number, y: number, tx: number, ty: number, req?: string) => E('ferry', id, x, y, { a: { x, y }, b: { x: tx, y: ty }, side: 0, req });
const socket = (id: string, x: number, y: number) => E('socket', id, x, y);
const sync = (id: string, x: number, y: number, role: 'fire' | 'water') => E('sync', id, x, y, { role });
const exit = (x: number, y: number, role: 'fire' | 'water') => E('exit', 'OUT', x, y, { role });
const fragment = (x: number, y: number, req = '') => E('fragment', '◇', x, y, { req });

